def panel_rows(cid, abilities, leader, describe_leader):
    char = BY_ID[str(cid)]
    result = {"desc_override_" + char.code: [[describe_leader]]}
    for slot, text in enumerate(TEXTS[char.cid], 1):
        rows = abilities[char.cid + str(slot)]
        if rows[0][0] != char.code + f"_{slot}":
            raise ValueError("panel string_id differs from battle rows")
        if char.cid == "129998":
            text = text.replace("个人魂", "层怨念")
        elif char.cid == "129996":
            text = text.replace("泡沫", "泡沫外衣")
        elif char.cid == "159999":
            text = text.replace("警戒协议", "交战模式")
            if slot == 6:
                text = text.replace("获得交战模式", "获得交战模式，持续15秒")
        result["desc_override_" + rows[0][0]] = [[(MAIN if slot == 3 else "") + text]]
    return result
