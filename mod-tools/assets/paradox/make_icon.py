"""PARADOX 图标：以诅咒武器「孤注一掷」20×20 剑为底，程序化改色（莫比乌斯黑白对剖 + 紫金护手）。"""
from PIL import Image

SRC = str(__import__("pathlib").Path(__file__).resolve().parents[1] / "cursed-weapons/all_in_blade_lv0.png")
OUT = str(__import__("pathlib").Path(__file__).resolve().parent / "paradox.png")
im = Image.open(SRC).convert("RGBA")
px = im.load()
OUTLINE = (24, 24, 42, 255)
BLADE = {(228, 237, 247), (165, 191, 213), (112, 126, 151), (208, 227, 241), (125, 139, 167), (202, 202, 223),
         (100, 109, 138), (68, 74, 105), (88, 91, 119)}
LIGHT = {(228, 237, 247): (255, 255, 255), (208, 227, 241): (236, 236, 244), (202, 202, 223): (222, 220, 236),
         (165, 191, 213): (206, 204, 222), (125, 139, 167): (182, 178, 204), (112, 126, 151): (170, 166, 194),
         (100, 109, 138): (150, 146, 178), (88, 91, 119): (140, 136, 168), (68, 74, 105): (120, 116, 150)}
DARK = {(228, 237, 247): (92, 84, 124), (208, 227, 241): (80, 72, 112), (202, 202, 223): (72, 64, 102),
        (165, 191, 213): (64, 56, 92), (125, 139, 167): (52, 46, 78), (112, 126, 151): (46, 40, 70),
        (100, 109, 138): (40, 34, 62), (88, 91, 119): (36, 30, 56), (68, 74, 105): (30, 26, 48)}
PURPLE = {(250, 60, 70): (190, 130, 255), (200, 16, 48): (140, 70, 220), (130, 8, 40): (92, 40, 160),
          (177, 1, 42): (110, 50, 180), (108, 26, 44): (70, 30, 120), (140, 41, 62): (96, 50, 150),
          (223, 46, 41): (160, 100, 240), (255, 210, 220): (230, 210, 255)}
RING = (10, 11)     # 刃中段一圈金环（x+y 为常数的一条斜线 = 垂直于刃）：莫比乌斯扭转的提示
GOLD = {10: (245, 193, 57), 11: (207, 131, 30)}
for y in range(20):
    for x in range(20):
        r, g, b, a = px[x, y]
        if a == 0:
            continue
        c = (r, g, b)
        if c in BLADE and x + y <= 22:           # 刃体（护手以上）
            if x + y in RING:
                px[x, y] = GOLD[x + y] + (255,)
            elif y < x:
                px[x, y] = LIGHT[c] + (255,)
            elif y > x:
                px[x, y] = DARK[c] + (255,)
            else:                                  # 刃脊
                px[x, y] = (196, 192, 220, 255)
        elif c in PURPLE:
            px[x, y] = PURPLE[c] + (255,)
im.save(OUT)
print("ok")
